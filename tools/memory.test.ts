import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";

const tools = join(resolve(dirname(fileURLToPath(import.meta.url)), ".."), "tools");

function isolated(run: (home: string) => void): void {
  const home = realpathSync(mkdtempSync(join(tmpdir(), "memory home ")));

  try {
    run(home);
  } finally {
    rmSync(home, { recursive: true, force: true });
  }
}

const invoke = (home: string, cwd: string, tool: string, ...args: string[]) =>
  spawnSync(process.execPath, [join(tools, tool), ...args], {
    cwd,
    env: { ...process.env, HOME: home },
    encoding: "utf8",
  });

function write(path: string, text: string) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
}

function seed(home: string) {
  const project = join(home, ".agents", "projects", "dev", "app");
  write(
    join(home, ".agents", "MEMORY.md"),
    "# Memory\n\n## Rules\n\n- Always use Effect in TypeScript.\n- Prefer pnpm.\n",
  );
  write(
    join(project, "MEMORY.md"),
    "# App memory\n\n## Decisions\n\n- 2026-11-19 Use Electron for the launcher:\n  pinned Chromium.\n\nLauncher builds run on CI only.\n",
  );
  write(
    join(home, ".agents", "projects", "dev", "other", "MEMORY.md"),
    "# Other\n\n- Electron is banned here.\n",
  );
  write(
    join(project, "tasks", "001-launcher", "TASK.md"),
    '---\ntitle: "Desktop launcher"\nstatus: inprogress\n---\n\nstatus: not this one\n',
  );
  write(join(project, "tasks", "001-launcher", "PLAN.md"), "# Plan\n");
  write(join(project, "tasks", "001-launcher", "INTENT.md"), "# Intent\n");
  write(
    join(project, "tasks", "001-launcher", "subtasks", "001-icons", "TASK.md"),
    "---\ntitle: Icons\nstatus: done\n---\n",
  );
  write(join(project, "tasks", "002-legacy", "TASK.html"), "<p>old</p>");

  return project;
}

test("tasks-index writes one line per task and subtask from TASK.md frontmatter", () =>
  isolated((home) => {
    const project = seed(home);
    const result = invoke(home, join(project, "tasks", "001-launcher"), "tasks-index.ts");
    assert.equal(result.status, 0, result.stderr);
    assert.equal(
      readFileSync(join(project, "TASKS.md"), "utf8"),
      [
        "# dev/app tasks",
        "",
        "<!-- Generated by tasks-index from each task's TASK.md; do not edit. -->",
        "",
        "- [001-launcher](tasks/001-launcher/TASK.md) · inprogress · Desktop launcher — [INTENT](tasks/001-launcher/INTENT.md) · [PLAN](tasks/001-launcher/PLAN.md)",
        "  - [001-icons](tasks/001-launcher/subtasks/001-icons/TASK.md) · done · Icons",
        "- [002-legacy](tasks/002-legacy/) · unknown · 002-legacy",
        "",
      ].join("\n"),
    );
  }));

test("recall returns matching bullets and paragraphs from global and current project memory, best first", () =>
  isolated((home) => {
    const project = seed(home);
    const result = invoke(home, project, "recall.ts", "electron", "launcher");
    assert.equal(result.status, 0, result.stderr);
    const [first, second] = result.stdout.split("\n\n");
    assert.equal(
      first,
      "projects/dev/app/MEMORY.md:5 › App memory › Decisions\n- 2026-11-19 Use Electron for the launcher:\n  pinned Chromium.",
    );
    assert.match(
      second ?? "",
      /^projects\/dev\/app\/MEMORY.md:8 .*\nLauncher builds run on CI only\.$/,
    );
    assert.doesNotMatch(result.stdout, /banned/);

    const global = invoke(home, project, "recall.ts", "EFFECT");
    assert.match(global.stdout, /^MEMORY.md:5 › Memory › Rules\n- Always use Effect/);
    assert.doesNotMatch(global.stdout, /pnpm/);
  }));

test("recall --all searches every project; a git checkout maps to its project", () =>
  isolated((home) => {
    seed(home);
    assert.match(invoke(home, home, "recall.ts", "banned", "--all").stdout, /Electron is banned/);
    const checkout = join(home, "dev", "app");
    mkdirSync(join(checkout, "src"), { recursive: true });
    spawnSync("git", ["init", "-q", checkout]);
    assert.match(
      invoke(home, join(checkout, "src"), "recall.ts", "chromium").stdout,
      /pinned Chromium/,
    );
    assert.match(
      invoke(home, home, "recall.ts", "nothing-here").stdout,
      /^No matches in MEMORY.md/,
    );
    assert.notEqual(invoke(home, home, "recall.ts").status, 0);
  }));
