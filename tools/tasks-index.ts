#!/usr/bin/env node
// tasks-index [project]: regenerate ~/.agents/projects/<project>/TASKS.md, one line per task
// (status, title, links to TASK.md and its documents), from each task's TASK.md. The
// project defaults to the one holding the current directory.
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { projectOf, projectsRoot } from "./vault.ts";

function field(task: string, key: string): string | undefined {
  const frontmatter = task.match(/^---\n([\s\S]*?)\n---/)?.[1] ?? "";

  return frontmatter.match(new RegExp(`^${key}:\\s*["']?(.*?)["']?\\s*$`, "m"))?.[1];
}

function lines(directory: string, link: string, depth: number): string[] {
  if (!existsSync(directory)) return [];

  return readdirSync(directory, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && /^\d{3}-/.test(entry.name))
    .map((entry) => entry.name)
    .sort()
    .flatMap((name) => {
      const path = join(directory, name);
      const href = `${link}/${name}`;

      const task = existsSync(join(path, "TASK.md"))
        ? readFileSync(join(path, "TASK.md"), "utf8")
        : "";

      const documents = readdirSync(path)
        .filter((file) => file.endsWith(".md") && file !== "TASK.md")
        .sort()
        .map((file) => `[${file.slice(0, -3)}](${href}/${file})`);

      const line = [
        `${"  ".repeat(depth)}- [${name}](${href}/${task ? "TASK.md" : ""})`,
        field(task, "status") ?? "unknown",
        field(task, "title") ?? name,
      ].join(" · ");

      return [
        documents.length ? `${line} — ${documents.join(" · ")}` : line,
        ...lines(join(path, "subtasks"), `${href}/subtasks`, depth + 1),
      ];
    });
}

function main(): void {
  const project = process.argv[2] ?? projectOf(process.cwd());

  if (!project) throw new Error("No project here; pass one, e.g. tasks-index dev/GameBox");
  const root = join(projectsRoot, project);

  if (!existsSync(join(root, "tasks"))) throw new Error(`No tasks folder: ${join(root, "tasks")}`);

  const index = [
    `# ${project} tasks`,
    "",
    "<!-- Generated by tasks-index from each task's TASK.md; do not edit. -->",
    "",
    ...lines(join(root, "tasks"), "tasks", 0),
    "",
  ].join("\n");

  writeFileSync(join(root, "TASKS.md"), index);
  console.log(join(root, "TASKS.md"));
}

try {
  main();
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
}
